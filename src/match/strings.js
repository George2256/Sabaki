const dictionaries = {en, 'zh-Hans': zh, 'zh-Hant': hant}

// Rule names come from the teaching dictionary so both panels agree.
function t(language, key, params = {}) {
  const value =
    (dictionaries[language] || en)[key] ||
    en[key] ||
    teachingText(language, key, params)
  return value.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ''))
}

const superscript = (n) => String(n).replace(/\d/g, (d) => '⁰¹²³⁴⁵⁶⁷⁸⁹'[d])

// E-values span many orders of magnitude: 35, 4,800, 3.2×10⁵.
function formatEvidence(log10E) {
  if (log10E < 4) return Math.round(10 ** log10E).toLocaleString('en-US')
  const exponent = Math.floor(log10E)
  return `${(10 ** (log10E - exponent)).toFixed(1)}×10${superscript(exponent)}`
}

// The bound on an honest player's chance, 1/E.
function formatChance(log10E) {
  if (log10E < 9) return `1/${Math.round(10 ** log10E).toLocaleString('en-US')}`
  return `10⁻${superscript(Math.floor(log10E))}`
}

module.exports = {t, dictionaries, formatEvidence, formatChance}
